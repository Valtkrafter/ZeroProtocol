"""
Yoru - RUN v2 = the OLD sprint (Blender/Yoru_Run.blend, 0.6 s, 5 m/s) POLISHED.  Nothing is rebuilt: the gait, legs, spine, head of the old clip stay
exactly as they are (the user likes them); only the details are improved.  Builds the comparison work file: 'Poliert' (Neu) next to 'Alt'.
  1. the old clip is appended twice (the file is only read): Alt untouched, Neu = copy of its action 'Yoru_Run' -> 'Yoru_Run_v2'
  2. ARMS: the arm chains (clavicle, upper arm, forearm, hand, fingers, thumb) are replaced by the organic arm layer (build_lauf_v2_lib.ArmLayer, STYLE
     below: swing amplitudes of the old run, overlapping action clavicle -> upper arm -> elbow -> forearm roll -> wrist -> fingers, left and right not
     mirrored), then fitted against torso / thighs / gear / bust with the exact intersection test (fix_arms)
  3. TAIL (preview): the root is turned sideways and the joints get a sideways S so the tail reads from behind (the game drives its tail in code)
  4. face B, Cycles modifiers (endless loop), one floor lane per character that scrolls with the ground motion of the old gait
Collections: Run_v2_R<N> (Run_v2_R<N>_Neu, Run_v2_R<N>_Alt, floors and labels).  60 fps, frames 0 .. 359 (10 cycles of 36).
Background:  blender -b --factory-startup --python build_run_v2_polish.py -- <out .blend> <round number> [style json]
The style json overrides keys of STYLE; the special keys 'tail_yaw' (deg) and 'tail_s' (list of deg per joint) are handled here.
"""
import bpy, os, sys, math, json

SCRIPTS = r'C:\Users\valen\ZeroProtocol\Blender\scripts'
ns = {'__file__': os.path.join(SCRIPTS, 'build_lauf_v2_lib.py')}
exec(compile(open(ns['__file__'], encoding='utf-8').read(), ns['__file__'], 'exec'), ns)
LB = ns
NF = 36
X_NEU, X_ALT = -0.6, 0.6
PLAY_END = 359

# arm style of the polished run: the swing of the OLD run (a little more forward, a little more elbow opening behind) with the organic layers
STYLE_RUN = dict(
    phase=-0.03,                      # old run: the left arm is furthest forward at the right touchdown (phase 0); NTE -0.13; in between
    a0=0.0, a_fwd=22.0, a_back=38.0,  # upper arm swing about the shoulder from the plumb line: +22 forward (old 16), -38 back (old 38)
    warp=0.10, ease=0.28,             # forward drive a little quicker than the way back; a soft dwell at the extremes
    ab0=13.0, ab_arc=2.0,
    tw0=0.0, tw_u=5.0,
    carry=3.0, yaw_follow=0.4,
    el_min=60.0, el_max=100.0, lag_e=0.05,      # elbow flexion behind / in front (old 66 / 100); the elbow trails the upper arm a little
    pron0=6.0, pron=9.0, lag_p=0.10,            # forearm roll (the palm turns back at the back swing), trails
    wf0=8.0, wf=15.0, wd0=6.0, wd=8.0, lag_w=0.15, ribbon=1.0, k_flex=0.9, k_cross=0.6,   # the wrist follows the trail of the forearm
    cu=12.0, lag_f=0.22,
    asym_amp=0.94, asym_ph=0.025, asym_el=-3.0,
)


def build(rnd, style=None):
    log = LB['log']
    root = LB['coll']('Run_v2_R%d' % rnd)
    c_neu = LB['coll']('Run_v2_R%d_Neu' % rnd, root)
    c_alt = LB['coll']('Run_v2_R%d_Alt' % rnd, root)
    info = {}
    style = dict(style or {})
    gen = style.pop('gen', None)                         # a gait generated by build_run.py (with changed body parameters) instead of the old clip
    # --- Alt: the old clip, untouched
    alt, akids = LB['append_character'](LB['OLD_RUN'], c_alt, 'Alt', X_ALT)
    aact = alt.animation_data.action
    aact.name = 'Yoru_Run_Alt'
    info['alt_cycles_added'] = LB['make_cyclic'](aact)
    # --- Neu: the same clip, polished
    arm, kids = LB['append_character'](gen or LB['OLD_RUN'], c_neu, 'Neu', X_NEU)
    src = arm.animation_data.action
    act = src.copy()
    act.name = 'Yoru_Run_v2'
    act.use_fake_user = True
    slot = getattr(arm.animation_data, 'action_slot', None)
    arm.animation_data.action = act
    if slot is not None and hasattr(arm.animation_data, 'action_slot') and arm.animation_data.action_slot is None:
        arm.animation_data.action_slot = act.slots[0]
    src.use_fake_user = False
    info['cycles_added'] = LB['make_cyclic'](act)
    tail_yaw = style.pop('tail_yaw', 0.0)
    tail_s = style.pop('tail_s', None)
    st = dict(LB['STYLE'], **STYLE_RUN)
    st.update(style)
    n, diags = LB['apply_arm_layer'](arm, st, NF)
    el = [d[s]['elbow'] for d in diags for s in 'LR']
    tw = [d[s]['twist'] for d in diags for s in 'LR']
    wr = [d[s]['wrist'] for d in diags for s in 'LR']
    su = [d[s]['swing_u'] for d in diags for s in 'LR']
    info.update(arm_bones=n, elbow=(round(min(el), 1), round(max(el), 1)), forearm_roll=(round(min(tw), 1), round(max(tw), 1)),
                wrist_bend=(round(min(wr), 1), round(max(wr), 1)), upper_arm_swing=(round(min(su), 1), round(max(su), 1)))
    log('arm layer', json.dumps(info))
    info['arm_extra_deg'] = LB['fix_arms'](arm, NF)
    log('gear fit (extra outward turn of the upper arm, deg)', info['arm_extra_deg'])
    if tail_yaw:
        info['tail_turned_keys'] = LB['turn_tail'](arm, tail_yaw, NF)
    if tail_s:
        info['tail_s_keys'] = tail_s_curve(arm, tail_s, NF)
    info['face'] = LB['face_b'](arm)
    LB['make_lane']('Boden_Run_Neu', LB['GAIT_ALT'], -9.0, 0.0, root)
    LB['make_lane']('Boden_Run_Alt', LB['GAIT_ALT'], 0.0, 9.0, root)
    LB['make_label']('Label_Run_Neu', 'Poliert', X_NEU, root)
    LB['make_label']('Label_Run_Alt', 'Alt: Rennen', X_ALT, root)
    scene = bpy.context.scene
    scene.render.fps = 60
    scene.render.fps_base = 1.0
    scene.frame_start, scene.frame_end = 0, PLAY_END
    try:
        scene.sync_mode = 'FRAME_DROP'
    except Exception:
        pass
    scene.frame_set(0)
    info['meshes'] = [k.name for k in kids] + [k.name for k in akids]
    return info


def tail_s_curve(arm, yaws, nf):
    """sideways S of the tail: tail joint i (1 .. 8) is turned by yaws[i-1] degrees about the up axis of the pelvis (+ = towards her right) in every key,
    pivot at the joint's own head, so every turn carries all the joints behind it; cumulative like the pitch curve of the tail"""
    from mathutils import Vector, Quaternion, Matrix
    ad = arm.animation_data
    act = ad.action
    slot = getattr(ad, 'action_slot', None)
    pbs = arm.pose.bones
    hips = pbs['J_Bip_C_Hips']
    R_h = arm.data.bones['J_Bip_C_Hips'].matrix_local.to_quaternion()
    names = ['J_Opt_C_CatTail%d_01' % i for i in range(1, 9)]
    poses = LB['sample_poses'](arm, nf)
    ad.action = None                                     # the animation system must not overwrite the poses that are set by hand
    newQ = []
    for f in range(nf):
        for n, (lo, ro, sc) in poses[f].items():
            pbs[n].location, pbs[n].rotation_quaternion, pbs[n].scale = lo, ro, sc
        bpy.context.view_layer.update()
        D_h = hips.matrix.to_quaternion() @ R_h.inverted()
        up = (D_h @ Vector((0.0, 0.0, 1.0))).normalized()
        for n, dg in zip(names, yaws):                   # root first: the parent's new pose is in place when the child is converted
            if not dg:
                continue
            pb = pbs[n]
            M = pb.matrix.copy()
            h = M.translation.copy()
            Mn = Matrix.Translation(h) @ Quaternion(up, math.radians(dg)).to_matrix().to_4x4() @ Matrix.Translation(-h) @ M
            pb.rotation_quaternion = arm.convert_space(pose_bone=pb, matrix=Mn, from_space='POSE', to_space='LOCAL').decompose()[1]
            bpy.context.view_layer.update()
        newQ.append({n: pbs[n].rotation_quaternion.copy() for n in names})
    ad.action = act
    if slot is not None and hasattr(ad, 'action_slot'):
        ad.action_slot = slot
    return LB['write_quat_keys'](act, arm, newQ, nf)


def main():
    argv = sys.argv[sys.argv.index('--') + 1:]
    out, rnd = argv[0], int(argv[1])
    style = json.loads(open(argv[2], encoding='utf-8').read()) if len(argv) > 2 else None
    bpy.ops.wm.read_factory_settings(use_empty=True)
    info = build(rnd, style)
    LB['log']('run_v2 round', rnd, json.dumps(info))
    bpy.ops.wm.save_as_mainfile(filepath=out)
    LB['log']('saved', out)


if bpy.app.background and '--' in sys.argv and globals().get('__name__') == '__main__':
    main()
